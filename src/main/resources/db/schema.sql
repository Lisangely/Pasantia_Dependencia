-- Esquema de la biblioteca FAU-UCV.
-- Sirve en PostgreSQL 10 o posterior. En Windows 7 se usa PostgreSQL 13 o, si el instalador no arranca, PostgreSQL 10.
-- Ejecutar contra la base biblioteca_fau:
--   psql -U postgres -d biblioteca_fau -f schema.sql
--
-- Usuario inicial: admin
-- Contraseña inicial: 123

CREATE TABLE IF NOT EXISTS usuarios_sistema (
    id_usuario     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    apellido       VARCHAR(100) NOT NULL,
    usuario        VARCHAR(50)  NOT NULL UNIQUE,
    correo         VARCHAR(150) UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    rol            VARCHAR(20)  NOT NULL,
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    puede_eliminar BOOLEAN      NOT NULL DEFAULT FALSE,
    puede_actualizar BOOLEAN    NOT NULL DEFAULT FALSE,
    puede_crear    BOOLEAN      NOT NULL DEFAULT FALSE,
    puede_crear_libros BOOLEAN  NOT NULL DEFAULT FALSE,
    puede_crear_autores BOOLEAN NOT NULL DEFAULT FALSE,
    puede_crear_editoriales BOOLEAN NOT NULL DEFAULT FALSE,
    puede_crear_ubicaciones BOOLEAN NOT NULL DEFAULT FALSE,
    puede_crear_ejemplares BOOLEAN NOT NULL DEFAULT FALSE,
    puede_crear_lectores BOOLEAN NOT NULL DEFAULT FALSE,
    puede_crear_prestamos BOOLEAN NOT NULL DEFAULT FALSE,
    puede_crear_incidencias BOOLEAN NOT NULL DEFAULT FALSE,
    pregunta_1     VARCHAR(200),
    pregunta_2     VARCHAR(200),
    pregunta_3     VARCHAR(200),
    respuesta_1_hash VARCHAR(255),
    respuesta_2_hash VARCHAR(255),
    respuesta_3_hash VARCHAR(255),
    CONSTRAINT usuarios_sistema_rol_chk
        CHECK (rol IN ('administrador', 'ayudante'))
);

CREATE TABLE IF NOT EXISTS lectores (
    id_lector      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    apellido       VARCHAR(100) NOT NULL,
    cedula         VARCHAR(20)  NOT NULL UNIQUE,
    correo         VARCHAR(150) NOT NULL,
    telefono       VARCHAR(30)  NOT NULL,
    semestre       VARCHAR(20),
    carrera        VARCHAR(150),
    fecha_registro TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS autores (
    id_autor         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(150) NOT NULL,
    apellido         VARCHAR(150),
    nombre_completo  VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS editoriales (
    id_editorial INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS libros (
    id_libro                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                   VARCHAR(500) NOT NULL,
    id_editorial             INTEGER,
    tipo                     VARCHAR(100),
    fecha_publicacion        SMALLINT,
    fecha_original           VARCHAR(50),
    requiere_revision_fecha  BOOLEAN      NOT NULL DEFAULT FALSE,
    cota                     VARCHAR(100),
    observaciones            TEXT,
    CONSTRAINT libros_editorial_fk
        FOREIGN KEY (id_editorial) REFERENCES editoriales (id_editorial)
);

CREATE TABLE IF NOT EXISTS libro_autor (
    id_libro INTEGER NOT NULL,
    id_autor INTEGER NOT NULL,
    PRIMARY KEY (id_libro, id_autor),
    CONSTRAINT libro_autor_libro_fk
        FOREIGN KEY (id_libro) REFERENCES libros (id_libro),
    CONSTRAINT libro_autor_autor_fk
        FOREIGN KEY (id_autor) REFERENCES autores (id_autor)
);

CREATE TABLE IF NOT EXISTS ubicaciones (
    id_ubicacion       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ubicacion_original VARCHAR(100) NOT NULL,
    estanteria         VARCHAR(20),
    posicion           VARCHAR(20),
    requiere_revision  BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS ejemplares (
    id_ejemplar      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_ejemplar  INTEGER,
    disponible       BOOLEAN   NOT NULL DEFAULT TRUE,
    requiere_revision BOOLEAN  NOT NULL DEFAULT FALSE,
    fecha_creacion   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_libro         INTEGER   NOT NULL,
    id_ubicacion     INTEGER,
    CONSTRAINT ejemplares_libro_fk
        FOREIGN KEY (id_libro) REFERENCES libros (id_libro),
    CONSTRAINT ejemplares_ubicacion_fk
        FOREIGN KEY (id_ubicacion) REFERENCES ubicaciones (id_ubicacion)
);

CREATE TABLE IF NOT EXISTS prestamos (
    id_prestamo               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejemplar               INTEGER   NOT NULL,
    id_lector                 INTEGER   NOT NULL,
    registrado_por            INTEGER   NOT NULL,
    fecha_prestamo            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_devolucion_esperada TIMESTAMP,
    fecha_devolucion_real     TIMESTAMP,
    estado                    VARCHAR(20) NOT NULL DEFAULT 'prestado',
    CONSTRAINT prestamos_estado_chk
        CHECK (estado IN ('prestado', 'devuelto', 'perdido')),
    CONSTRAINT prestamos_ejemplar_fk
        FOREIGN KEY (id_ejemplar) REFERENCES ejemplares (id_ejemplar),
    CONSTRAINT prestamos_lector_fk
        FOREIGN KEY (id_lector) REFERENCES lectores (id_lector),
    CONSTRAINT prestamos_usuario_fk
        FOREIGN KEY (registrado_por) REFERENCES usuarios_sistema (id_usuario)
);

CREATE TABLE IF NOT EXISTS incidencias_datos (
    id_incidencia  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_libro       INTEGER      NOT NULL,
    campo          VARCHAR(100) NOT NULL,
    valor_original VARCHAR(255),
    descripcion    TEXT         NOT NULL,
    resuelto       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT incidencias_libro_fk
        FOREIGN KEY (id_libro) REFERENCES libros (id_libro)
);

CREATE TABLE IF NOT EXISTS auditoria (
    id_auditoria   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     INTEGER,
    fecha_evento   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    entidad        VARCHAR(50) NOT NULL,
    id_entidad     INTEGER     NOT NULL,
    accion         VARCHAR(30) NOT NULL,
    valor_anterior TEXT,
    valor_nuevo    TEXT,
    observaciones  TEXT,
    CONSTRAINT auditoria_accion_chk
        CHECK (accion IN (
            'INSERT',
            'UPDATE',
            'DELETE',
            'PRESTAMO',
            'DEVOLUCION',
            'RESOLVER_INCIDENCIA',
            'LOGIN'
        )),
    CONSTRAINT auditoria_usuario_fk
        FOREIGN KEY (id_usuario) REFERENCES usuarios_sistema (id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_libros_titulo ON libros (titulo);
CREATE INDEX IF NOT EXISTS idx_libros_cota ON libros (cota);
CREATE INDEX IF NOT EXISTS idx_ejemplares_libro ON ejemplares (id_libro);
CREATE INDEX IF NOT EXISTS idx_prestamos_ejemplar_estado ON prestamos (id_ejemplar, estado);
CREATE INDEX IF NOT EXISTS idx_incidencias_libro_resuelto ON incidencias_datos (id_libro, resuelto);
CREATE INDEX IF NOT EXISTS idx_auditoria_entidad ON auditoria (entidad, id_entidad);

